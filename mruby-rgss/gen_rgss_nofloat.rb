# frozen_string_literal: true

# Generates the no-Float (MRB_NO_FLOAT) copy of mrblib/lib.rb: the block between FLOAT-BEGIN and FLOAT-END (the unit
# and fractions the Ruby side passes the native layer) is replaced by its Integer form. Zoom and angle are whole
# numbers there (unit is 1). A transition fraction is an Integer in 1/1024 units (1024 == 1.0), which the native
# layer divides back out (rgss_fraction in src/lib.cxx). The four names are the same in both forms, so the rest of
# lib.rb is the same text. The output is checked to hold no Float literal: a no-Float VM would not compile one.
#
# Usage: ruby gen_rgss_nofloat.rb <mrblib/lib.rb> <output.rb>
SRC = ARGV.fetch(0)
OUT = ARGV.fetch(1)

INTEGER_BLOCK = <<-RUBY
  # FLOAT-BEGIN: no-Float build (generated by gen_rgss_nofloat.rb). Zoom and angle are whole numbers; a transition
  # fraction is an Integer in 1/1024 units (1024 == 1.0).
  def self.unit; 1 end
  def self.half; 512 end
  def self.fraction(n, d); n * 1024 / d end
  def self.brightness(v); v * 1024 / 255 end
  # FLOAT-END
RUBY


text = File.read(SRC)
begin_mark = "  # FLOAT-BEGIN"
end_mark = "  # FLOAT-END\n"
b = text.index(begin_mark) or raise "no FLOAT-BEGIN in #{SRC}"
e = text.index(end_mark, b) or raise "no FLOAT-END in #{SRC}"
out = text[0...b] + INTEGER_BLOCK + text[(e + end_mark.size)..]

literal = out.lines.reject { |l| l.lstrip.start_with?('#') }.grep(/(?<![\w.])\d+\.\d+(?:e[-+]?\d+)?(?![\w.])/)
unless literal.empty?
  warn 'gen_rgss_nofloat: Float literal left in the no-Float output:'
  literal.each { |l| warn "  #{l.strip}" }
  exit 1
end
if out.match?(/\.to_f\b/)
  warn 'gen_rgss_nofloat: .to_f left in the no-Float output'
  exit 1
end

File.write(OUT, out)
warn "gen_rgss_nofloat: wrote #{OUT}"
