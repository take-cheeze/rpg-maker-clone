#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates mrblib/save_typed_accessors.rb: one typed reader per field of the
# save schema (LCF::Schema::SAVE_DATA and every SAVE_* table it reaches), so
# each saved field has a declared Ruby class (see SaveTyped.fits? in
# mrblib/save_typed.rb for the mapping) and LCF::SaveData's reader can check
# every field against it when a save is read (docs/adr/0400).
#
# Usage:
#   ruby mruby-lcf/gen_save_typed_accessors.rb [OUT]        # write (default: mrblib/save_typed_accessors.rb and save_typed_setters.rb)
#   ruby mruby-lcf/gen_save_typed_accessors.rb --check      # exit 1 when the committed file is stale
#
# This only reads schema.rb (the single source of
# truth, loadable by CRuby) and never edits it. Accessors are emitted as
# plain, explicit methods rather than define_method, because mrblib/ of this
# gem is compiled by bc2cpp as a closed world (AGENTS.md).

MRBLIB = File.expand_path('mrblib', __dir__)
OUT = File.join(MRBLIB, 'save_typed_accessors.rb')
SETTERS_OUT = File.join(MRBLIB, 'save_typed_setters.rb')

# Fields the reader deliberately does not check on load. Chunk 113/114's
# execution-state stack (SAVE_EVENT_EXEC_STATE field 1) has been tolerated
# since before this check existed: a genuine EasyRPG F9-debug save carries a
# stack whose bytes do not decode as this schema, and it must keep loading
# with that event simply restarting (see Game::State.read_event_exec_frames).
# Those frames are still read, typed, through EventExecState#frames.
UNCHECKED = { 'SAVE_EVENT_EXEC_STATE' => [1] }.freeze

module GenSaveTyped
  module_function

  # Defines LCF::Schema from schema.rb unless a caller (a check script that
  # already loaded it) has done so: schema.rb's constants cannot be redefined.
  def load_schema
    return if defined?(LCF::Schema)
    TOPLEVEL_BINDING.eval(File.read(File.join(MRBLIB, 'schema.rb')), File.join(MRBLIB, 'schema.rb'))
  end

  def resolve(v)
    v.respond_to?(:call) ? v.call : v
  end

  # Constant name (e.g. :SAVE_MOVABLE) whose value is +obj+ (by identity). Aliases
  # (SAVE_FOREGROUND_EVENT = SAVE_EVENT_EXEC_STATE) share one object, so the name is
  # the alphabetically first one, not whichever constant the load order lists first.
  def const_name_of(consts, obj)
    hits = consts.select { |_, v| v.equal?(obj) }.keys.sort
    raise "save table without a SAVE_* constant (inline elements)" if hits.empty?
    hits.first
  end

  # Class name for a SAVE_* constant: SAVE_EVENT_EXEC_FRAME -> EventExecFrame,
  # SAVE_DATA -> Save.
  def class_name(const)
    return 'Save' if const == :SAVE_DATA
    s = const.to_s.sub(/\ASAVE_/, '')
    s.split('_').map { |w| w.capitalize }.join
  end

  def tables
    # Every schema table a save reaches is either a SAVE_* constant or a shared
    # one (SAVE_SYSTEM's BGM/SE fields point at the bare BGM/SE constants).
    consts = {}
    LCF::Schema.constants.each do |c|
      v = LCF::Schema.const_get(c)
      consts[c] = v if v.is_a?(Hash) || v.respond_to?(:call)
    end
    order = []
    seen = {}
    queue = [:SAVE_DATA]
    fields = {}
    until queue.empty?
      const = queue.shift
      next if seen[const]
      seen[const] = true
      order << const
      value = resolve(consts[const])
      # SAVE_DATA is the file's wrapper ({ name:, type:, elements: }); every
      # other SAVE_* constant is the field map itself.
      rows = const == :SAVE_DATA ? resolve(value[:elements]) : value
      fields[const] = rows.sort_by { |id, _| id }.map do |id, f|
        child = nil
        if f[:elements]
          child = const_name_of(consts, f[:elements])
          queue << child
        end
        [id, f, child]
      end
    end
    [order, fields]
  end

  def snake(name)
    raise "field name #{name.inspect} is not a plain identifier" unless name.to_s =~ /\A[a-z][a-z0-9_]*\z/
    name.to_s
  end

  PREFIX = 'save_'

  def generate
    load_schema
    order, fields = tables
    reserved = Object.instance_methods.map(&:to_s) + %w[rec path read table rows check! frame frames save_put save_link]
    out = +''
    out << "# Generated by mruby-lcf/gen_save_typed_accessors.rb from mrblib/schema.rb -- do not edit.\n"
    out << "# One typed reader per save-schema field (docs/adr/0400). A reader returns the\n"
    out << "# field's decoded value (its schema default when absent), checked against the\n"
    out << "# Ruby class its schema type declares (see SaveTyped.fits?). A nested table\n"
    out << "# returns its own typed record; a nested Array2D returns the table with each\n"
    out << "# row checked.\n"
    out << "\nmodule LCF\n  module SaveTyped\n"
    order.each do |const|
      cls = class_name(const)
      out << "\n    class #{cls} < Record\n"
      names = []
      checked = []
      fields[const].each do |id, f, child|
        # Every reader carries the save_ prefix, so a field named like a game method
        # (zoom, font, level, type) cannot add a candidate to that method's dispatch.
        field = snake(f[:name])
        name = PREFIX + field
        raise "#{cls}.#{name} collides with a reserved name" if reserved.include?(name)
        raise "#{cls}.#{name} is declared twice" if names.include?(name)
        names << name
        body =
          if f[:type] == :Array1D && child
            "table #{id}, #{class_name(child)}, :#{field}"
          elsif f[:type] == :Array2D && child
            "rows #{id}, #{class_name(child)}, :#{field}"
          else
            "read #{id}, :#{f[:type]}, :#{field}"
          end
        out << "      def #{name}; #{body} end\n"
        checked << name unless (UNCHECKED[const.to_s] || []).include?(id)
      end
      out << "\n      # Reads every declared field, so a field whose bytes do not decode as its\n"
      out << "      # schema type raises LCF::SaveTypeError here, not at a later lookup.\n"
      out << "      def check!\n"
      checked.each { |n| out << "        #{n}\n" }
      out << "        self\n      end\n"
      out << "    end\n"
    end
    out << "  end\nend\n"
    out
  end

  # mrblib/save_typed_setters.rb: one typed writer per field, the write side of the
  # readers above (docs/adr/0407). A writer checks the value's class against the
  # field's schema type and stores it through LCF::Array1D#[]=, which encodes by the
  # schema, so the bytes written are exactly those of `rec[id] = value`. Field names
  # are Symbols (never String literals): a string literal in the generated
  # code broke bc2cpp's static-dispatch proof in docs/adr/0400.
  def generate_setters
    load_schema
    order, fields = tables
    out = +''
    out << "# Generated by mruby-lcf/gen_save_typed_accessors.rb from mrblib/schema.rb -- do not edit.\n"
    out << "# One typed writer per save-schema field (docs/adr/0407), the write side of\n"
    out << "# save_typed_accessors.rb. `rec.save_x = v` checks v against the field's schema\n"
    out << "# type and stores it through LCF::Array1D#[]= (the schema encoder), so the bytes\n"
    out << "# are those of `array1d[id] = v`. nil drops the chunk.\n"
    out << "\nmodule LCF\n  module SaveTyped\n"
    order.each do |const|
      out << "\n    class #{class_name(const)} < Record\n"
      fields[const].each do |id, f, _child|
        field = snake(f[:name])
        out << "      def #{PREFIX}#{field}=(v); save_put #{id}, v end\n"
      end
      out << "    end\n"
    end
    out << "  end\nend\n"
    out
  end
end

if __FILE__ == $PROGRAM_NAME
  # Under CRuby the mruby-lcf runtime (Record/read/table/rows, the SaveTyped
  # helpers) is needed only to resolve class names of the generated code; the
  # generator itself needs just LCF::Schema, so it defines LCF bare here.
  module LCF; end
  text = GenSaveTyped.generate
  setters = GenSaveTyped.generate_setters
  if ARGV[0] == '--check'
    stale = [[OUT, text], [SETTERS_OUT, setters]].reject { |path, want| (File.read(path) rescue '') == want }
    if stale.empty?
      puts 'save_typed_accessors.rb and save_typed_setters.rb are up to date'
    else
      warn "#{stale.map(&:first).join(', ')} stale: run ruby mruby-lcf/gen_save_typed_accessors.rb"
      exit 1
    end
  elsif ARGV[0]
    File.write(ARGV[0], text)
    puts "wrote #{ARGV[0]} (#{text.bytesize} bytes)"
  else
    File.write(OUT, text)
    File.write(SETTERS_OUT, setters)
    puts "wrote #{OUT} (#{text.bytesize} bytes), #{SETTERS_OUT} (#{setters.bytesize} bytes)"
  end
end
