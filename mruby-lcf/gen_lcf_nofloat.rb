# frozen_string_literal: true

# Generates the no-Float (MRB_NO_FLOAT) copy of mrblib/lcf.rb: the block between
# FLOAT-CODEC-BEGIN and FLOAT-CODEC-END (the IEEE-754 Float codec) is replaced by
# the fixed-point codec, where a :double save value is an Integer in 1/1024
# units. The same four names (double_decode, double_encode, double_value?,
# double_default) exist in both, so the rest of lcf.rb and the readers are the
# same text. The output is checked to hold no Float literal: a no-Float VM would
# not compile one.
#
# Usage: ruby gen_lcf_nofloat.rb <mrblib/lcf.rb> <output.rb>
SRC = ARGV.fetch(0)
OUT = ARGV.fetch(1)

FIXED_BLOCK = <<~RUBY
  # FLOAT-CODEC-BEGIN: no-Float build (generated by gen_lcf_nofloat.rb). A :double save value is an Integer in
  # 1/1024 units (SHIFT 10), decoded and encoded with the integer-only codec above.
  def self.double_decode d; unpack_fixed_double(d, 10) end
  def self.double_encode v; pack_fixed_double(v, 10) end
  def self.double_value? v; v.is_a?(Integer) end
  def self.double_default whole; whole << 10 end
  # FLOAT-CODEC-END
RUBY

text = File.read(SRC)
begin_mark = "  # FLOAT-CODEC-BEGIN"
end_mark = "  # FLOAT-CODEC-END\n"
b = text.index(begin_mark) or raise "no FLOAT-CODEC-BEGIN in #{SRC}"
e = text.index(end_mark, b) or raise "no FLOAT-CODEC-END in #{SRC}"
out = text[0...b] + FIXED_BLOCK + text[(e + end_mark.size)..]

literal = out.lines.reject { |l| l.lstrip.start_with?('#') }.grep(/(?<![\w.])\d+\.\d+(?:e[-+]?\d+)?(?![\w.])/)
unless literal.empty?
  warn "gen_lcf_nofloat: Float literal left in the no-Float output:"
  literal.each { |l| warn "  #{l.strip}" }
  exit 1
end

File.write(OUT, out)
warn "gen_lcf_nofloat: wrote #{OUT}"
